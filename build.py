"""Rebuild images/ and artworks.js from the submissions export.

Usage: python build.py <export.csv> <folder of chosen pieces>

Only files present in the folder are published. Images are resized, rotated
upright and saved without metadata (phone photos can carry GPS location).
"""
import csv
import json
import os
import re
import sys

import fitz
from PIL import Image, ImageOps

MAX_SIDE = 2000
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "images")


def load(path):
    if path.lower().endswith(".pdf"):
        page = fitz.open(path)[0]
        zoom = MAX_SIDE / max(page.rect.width, page.rect.height)
        pix = page.get_pixmap(matrix=fitz.Matrix(zoom, zoom), alpha=False)
        return Image.frombytes("RGB", (pix.width, pix.height), pix.samples)
    img = ImageOps.exif_transpose(Image.open(path))
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        bg = Image.new("RGB", img.size, "white")
        bg.paste(img, mask=img.split()[-1])
        return bg
    return img.convert("RGB")


def main(csv_path, pieces_dir):
    with open(csv_path, encoding="utf-8-sig") as f:
        rows = {os.path.basename(r["artwork_path"]).lower(): r
                for r in csv.DictReader(f, delimiter=";")}

    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        os.remove(os.path.join(OUT, old))

    art, used = [], set()
    for name in sorted(os.listdir(pieces_dir)):
        row = rows.get(name.lower())
        if not row:
            continue
        first = row["first_name"].strip().split()[0].capitalize()
        slug = re.sub(r"[^a-z0-9]+", "-", first.lower()).strip("-")
        out, n = slug, 2
        while out in used:
            out, n = f"{slug}-{n}", n + 1
        used.add(out)

        img = load(os.path.join(pieces_dir, name))
        img.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
        img.save(os.path.join(OUT, out + ".jpg"), "JPEG", quality=85, optimize=True, progressive=True)
        art.append({
            "image": out + ".jpg",
            "name": first,
            "age": int(row["age"]),
            "title": row["title"].strip().strip("«»\"'").strip(),
            "w": img.width,
            "h": img.height,
        })
        print(f"{name} -> {out}.jpg {img.width}x{img.height}")

    with open(os.path.join(HERE, "artworks.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build.py. One entry per art piece, shown in this order.\n")
        f.write("const ARTWORKS = " + json.dumps(art, indent=2, ensure_ascii=False) + ";\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
